// One-time: create the OTA signing key pair.
//   private key -> .ota-keys/ota-private.pem  (gitignored; BACK IT UP OFFLINE, never share it)
//   public key  -> android/src/components/update-keys.js (compiled into the APK)
import { generateKeyPairSync } from "crypto";
import { existsSync, mkdirSync, writeFileSync, chmodSync } from "fs";
import { dirname, join } from "path";
import { ROOT, ANDROID, KEY_FILE, fail } from "./lib/common.mjs";

if (existsSync(KEY_FILE)) fail(`${KEY_FILE} already exists. Refusing to overwrite: replacing it would lock installed apps out of OTA updates.`);

const { publicKey, privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
mkdirSync(dirname(KEY_FILE), { recursive: true });
writeFileSync(KEY_FILE, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
try { chmodSync(KEY_FILE, 0o600); } catch { /* Windows */ }

const spki = publicKey.export({ type: "spki", format: "der" }).toString("base64");
writeFileSync(join(ANDROID, "src", "components", "update-keys.js"),
  `/** OTA signature public key (ECDSA P-256, SPKI base64). Generated by scripts/ota-keygen.mjs. Safe to publish. */\nwindow.UPDATE_PUBLIC_KEY = "${spki}";\n`);
console.log("✅ Key pair created.");
console.log("   Private key:", KEY_FILE, "→ back this up offline. Do NOT commit it.");
console.log("   Public key written to android/src/components/update-keys.js (rebuild + ship a new APK to embed it).");
